export class ShopifyService {
  static getAllProducts(filter = {}) {
    let list = [...PRODUCTS_CATALOG];
    if (filter.category) {
      const catLower = filter.category.toLowerCase();
      list = list.filter(p => 
        p.category.toLowerCase().includes(catLower) || 
        p.categorySlug.toLowerCase() === catLower
      );
    }
    if (filter.search) {
      const q = filter.search.toLowerCase();
      list = list.filter(p => 
        p.name.toLowerCase().includes(q) || 
        p.scentNotes.toLowerCase().includes(q) ||
        p.description.toLowerCase().includes(q) ||
        p.category.toLowerCase().includes(q)
      );
    }
    return list;
  }

  static getProductById(id) {
    const numId = Number(id);
    return PRODUCTS_CATALOG.find(p => p.id === numId) || null;
  }

  static getCollections() {
    return COLLECTIONS;
  }

  static getCollectionBySlug(slug) {
    return COLLECTIONS.find(c => c.id === slug || c.title.toLowerCase() === slug.toLowerCase()) || null;
  }
}

export default ShopifyService;
